"""Migrations must apply, roll back, and match the SQLAlchemy models exactly."""

from alembic import command
from sqlalchemy import create_engine, inspect
from sqlalchemy.pool import NullPool

from tests.db.conftest import alembic_config

CRM_TABLES = {
    "tenants",
    "users",
    "accounts",
    "contacts",
    "leads",
    "portal_access_grants",
    "opportunities",
    "lead_activities",
    "lead_assignments",
    "audit_log",
}


def _tables(url: str) -> set[str]:
    engine = create_engine(url, poolclass=NullPool)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade_roundtrip(migrated_database: str) -> None:
    config = alembic_config(migrated_database)
    assert CRM_TABLES <= _tables(migrated_database)

    command.downgrade(config, "base")
    assert CRM_TABLES.isdisjoint(_tables(migrated_database))

    command.upgrade(config, "head")
    assert CRM_TABLES <= _tables(migrated_database)


def test_models_and_migrations_are_in_sync(migrated_database: str) -> None:
    # Fails (AutoGenerateDiffsDetected) if a model was changed without a new migration.
    command.check(alembic_config(migrated_database))
