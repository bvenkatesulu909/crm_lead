"""Document metadata (ADR 0005). The bytes live in the S3 file store, never in PostgreSQL."""

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    UniqueConstraint,
    Uuid,
    func,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.core.models import Base, TenantOwnedMixin, UUIDPrimaryKeyMixin

# Records a document can belong to, and why it exists. Extended as modules start using it.
RECORD_TYPES = ("quote", "account", "opportunity")
# quote_pdf: generated by the system (one per quote); quote_deck: the proposal deck (ADR 0032;
# one per quote and content); attachment: uploaded by people.
PURPOSES = ("quote_pdf", "attachment", "quote_deck")


def _sql_list(values: tuple[str, ...]) -> str:
    # "('a', 'b')" - unlike str(tuple), no trailing comma for a single value.
    return "(" + ", ".join(f"'{v}'" for v in values) + ")"


class Document(UUIDPrimaryKeyMixin, TenantOwnedMixin, Base):
    __tablename__ = "documents"
    __table_args__ = (
        UniqueConstraint("tenant_id", "id"),
        UniqueConstraint("storage_key"),
        CheckConstraint(f"record_type IN {_sql_list(RECORD_TYPES)}", name="record_type_allowed"),
        CheckConstraint(f"purpose IN {_sql_list(PURPOSES)}", name="purpose_allowed"),
        CheckConstraint("size_bytes >= 0", name="size_not_negative"),
        CheckConstraint("sha256 ~ '^[0-9a-f]{64}$'", name="sha256_hex"),
        # Each quote has at most one generated PDF.
        Index(
            "uq_documents_one_generated_per_record",
            "tenant_id",
            "record_type",
            "record_id",
            "purpose",
            unique=True,
            postgresql_where=text("purpose = 'quote_pdf'"),
        ),
        # A proposal deck with the same bytes is stored once per quote (ADR 0032).
        Index(
            "uq_documents_quote_deck_content",
            "tenant_id",
            "record_type",
            "record_id",
            "sha256",
            unique=True,
            postgresql_where=text("purpose = 'quote_deck'"),
        ),
        # Versions of one document: 1, 2, 3, ... - never two with the same number.
        UniqueConstraint("tenant_id", "group_id", "version_no"),
        CheckConstraint("version_no >= 1", name="version_positive"),
        Index("ix_documents_tenant_id_record", "tenant_id", "record_type", "record_id"),
        ForeignKeyConstraint(
            ["tenant_id", "created_by_user_id"],
            ["users.tenant_id", "users.id"],
            ondelete="RESTRICT",
        ),
    )

    record_type: Mapped[str] = mapped_column(String(30))
    record_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    purpose: Mapped[str] = mapped_column(String(30))
    file_name: Mapped[str] = mapped_column(String(200))
    content_type: Mapped[str] = mapped_column(String(100))
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64))
    # tenant/{tenant_id}/{area}/{record_id}/{document_id} - built by the server only.
    storage_key: Mapped[str] = mapped_column(String(300))
    customer_visible: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    # NULL when the system (the worker) created it.
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, default=None)
    # clock_timestamp(), not now(): two decks made in one transaction still sort in order.
    created_at: Mapped[datetime] = mapped_column(server_default=func.clock_timestamp())
    # All versions of one document share a group id (the first version's id).
    group_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    version_no: Mapped[int] = mapped_column(Integer, server_default=text("1"))
    description: Mapped[str | None] = mapped_column(String(500), default=None)


UPLOAD_STATUSES = ("pending", "finished", "failed", "expired")
UPLOAD_RECORD_TYPES = ("account", "opportunity")


class DocumentUpload(UUIDPrimaryKeyMixin, TenantOwnedMixin, Base):
    """An upload a person started (ADR 0025): checked before the bytes arrive, the file then goes
    straight to ``pending/{tenant}/{id}`` in the store, and ``finish`` makes it a document after the
    same checks as a normal upload. Short-lived: the worker deletes rows a day old."""

    __tablename__ = "document_uploads"
    __table_args__ = (
        UniqueConstraint("tenant_id", "id"),
        CheckConstraint(
            f"record_type IN {_sql_list(UPLOAD_RECORD_TYPES)}", name="record_type_allowed"
        ),
        CheckConstraint(f"status IN {_sql_list(UPLOAD_STATUSES)}", name="status_allowed"),
        CheckConstraint("declared_size >= 1", name="declared_size_positive"),
        CheckConstraint(
            "(status = 'finished') = (document_id IS NOT NULL)", name="finished_has_document"
        ),
        Index(
            "ix_document_uploads_tenant_id_user_created",
            "tenant_id",
            "created_by_user_id",
            "created_at",
        ),
        ForeignKeyConstraint(
            ["tenant_id", "created_by_user_id"],
            ["users.tenant_id", "users.id"],
            ondelete="CASCADE",
        ),
    )

    created_by_user_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    record_type: Mapped[str] = mapped_column(String(30))
    record_id: Mapped[uuid.UUID] = mapped_column(Uuid)
    file_name: Mapped[str] = mapped_column(String(200))
    content_type: Mapped[str] = mapped_column(String(100))
    declared_size: Mapped[int] = mapped_column(BigInteger)
    customer_visible: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    description: Mapped[str | None] = mapped_column(String(500), default=None)
    status: Mapped[str] = mapped_column(String(20), server_default=text("'pending'"))
    document_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, default=None)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    finished_at: Mapped[datetime | None] = mapped_column(default=None)
